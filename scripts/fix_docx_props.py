# -*- coding: utf-8 -*-
"""Rewrite docProps/core.xml for the two .docx uploads and drop the template thumbnail.

python-docx leaves ``<dc:creator>python-docx</dc:creator>``,
``<dc:description>generated by python-docx</dc:description>`` and a 2013-12-23
timestamp in every file it writes. Those are visible in the file's properties
dialog and in the editorial system's metadata view, so they are replaced with
the author and the revision date. ``docProps/thumbnail.jpeg`` is the stock
python-docx template preview and is removed together with its package
relationship; nothing in ``word/`` references it.

Usage:
    py -3.11 scripts/fix_docx_props.py --dir <upload dir>
"""

from __future__ import annotations

import argparse
import shutil
import zipfile
from pathlib import Path

CREATED = "2026-11-08T09:00:00Z"
AUTHOR = "Jiang Tao"

CORE = (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\r\n'
    '<cp:coreProperties'
    ' xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"'
    ' xmlns:dc="http://purl.org/dc/elements/1.1/"'
    ' xmlns:dcterms="http://purl.org/dc/terms/"'
    ' xmlns:dcmitype="http://purl.org/dc/dcmitype/"'
    ' xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
    "<dc:title>{title}</dc:title>"
    "<dc:subject>Neurocomputing major revision, NEUCOM-D-26-24287</dc:subject>"
    "<dc:creator>{author}</dc:creator>"
    "<cp:keywords/>"
    "<dc:description/>"
    "<cp:lastModifiedBy>{author}</cp:lastModifiedBy>"
    "<cp:revision>2</cp:revision>"
    '<dcterms:created xsi:type="dcterms:W3CDTF">{ts}</dcterms:created>'
    '<dcterms:modified xsi:type="dcterms:W3CDTF">{ts}</dcterms:modified>'
    "<cp:category/>"
    "</cp:coreProperties>"
)


def fix(path: Path, title: str) -> None:
    tmp = path.with_suffix(".docx.tmp")
    with zipfile.ZipFile(path) as src, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as dst:
        for item in src.infolist():
            name = item.filename
            if name == "docProps/thumbnail.jpeg":
                continue
            data = src.read(name)
            if name == "docProps/core.xml":
                data = CORE.format(title=title, author=AUTHOR, ts=CREATED).encode("utf-8")
            elif name == "_rels/.rels":
                text = data.decode("utf-8")
                # drop the thumbnail relationship only
                if 'Target="docProps/thumbnail.jpeg"' in text:
                    import re
                    text = re.sub(
                        r'<Relationship[^>]*Target="docProps/thumbnail\.jpeg"[^>]*/>', "", text
                    )
                data = text.encode("utf-8")
            dst.writestr(item, data)
    shutil.move(tmp, path)
    print(f"  {path.name}: core props set, thumbnail dropped")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    args = ap.parse_args()
    d = Path(args.dir)
    fix(d / "abstract.docx", "Abstract")
    fix(d / "highlights.docx", "Highlights")


if __name__ == "__main__":
    main()

# Files that belong in the LaTeX source archive. Anything built (aux, log, synctex)
# is regenerated by the recipient and only makes the zip confusing.
TEX_SUFFIXES = {".tex", ".bib", ".bbl", ".cls", ".sty", ".pdf", ".png", ".jpg"}

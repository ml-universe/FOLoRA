"""Assemble the files uploaded with the major revision.

Everything in the pack is derived from the repository or from the two built
PDFs; nothing is typed by hand except the checklist, which is generated from
the same facts so that its numbers cannot drift from the files.

Usage:
    py -3.11 scripts/build_submission_pack.py --out <dir>

The pack keeps the ASCII names quoted in the letter's file table (Sec. "Files
submitted with this revision"), so that the upload folder and the letter agree:

    response-to-reviewers.pdf   paper/response-letter/main.pdf
    main.pdf                    paper/main.pdf
    highlights.docx             (made by make_submission_docs.py)
    abstract.docx               (ditto)
    latex-source.zip            compile-relevant paper/ sources, flattened (no folders)
    figures.zip                 figures as standalone files (make_figures_zip.py)
    reports.zip                 reports JSON + per-run config.json
    revision-evidence-log.md    paper/revision-evidence-log.md (the English one-pager;
                                the Chinese reports/REVISION-LOG-<date>.md is internal
                                and is never packed)
    submission-checklist.md     generated below
"""


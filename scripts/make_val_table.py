# -*- coding: utf-8 -*-
"""生成 `paper/tables/tab_val_select.tex`：验证集重选表（回应 R8-6）。

数据只从 `reports/val_selection.json` 读，**不手写任何数字**：
    01_summary / 正文里的「选中的 λ」必须与这张表出自同一次汇总。

用法（项目根目录）：
    py -3.11 -m scripts.make_val_table            # 打印并写文件
    py -3.11 -m scripts.make_val_table --check    # 只校验磁盘版本是否与数据一致
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SRC = Path("reports/val_selection.json")
OUT = Path("paper/tables/tab_val_select.tex")


def build() -> str:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    by = d["by_lambda"]
    chosen = d["selected_lambda"]
    picks = d.get("per_seed_pick", {})
    vals = sorted(by, key=float)

    lines = [
        "% Generated by scripts/make_val_table.py; do not edit by hand.",
        r"\begin{table}[tbp]",
        r"\centering\small",
        r"\setlength{\tabcolsep}{6pt}",
        r"\caption{Validation-based re-selection of $\lambda$ on Split CIFAR-100. For each "
        r"candidate $\lambda$ the table gives the mean accuracy over the three seeds on a "
        r"held-out $10\%$ of the training samples (the \emph{selection} criterion) and on the "
        r"official test set (reported, never used to select). The withheld samples are the "
        r"same for every candidate at a given seed and are never trained on; the test set is "
        r"not consulted. The selected row is the one with the best held-out mean, and its "
        r"test accuracy is what a protocol that never sees the test set would have reported.}",
        r"\label{tab:val-select}",
        r"\begin{tabular}{@{}ccccc@{}}",
        r"\toprule",
        r"$\lambda$ & $n$ & Held-out $\overline{\mathrm{ACC}}$ & Test $\overline{\mathrm{ACC}}$"
        r" & Selected \\",
        r"\midrule",
    ]
    for lam in vals:
        r = by[lam]
        mark = r"$\checkmark$" if lam == chosen else ""
        lines.append(
            rf"{float(lam):g} & {r['n']} & {r['val_mean']*100:.2f}$\pm${r['val_std']*100:.2f}"
            rf" & {r['test_mean']*100:.2f}$\pm${r['test_std']*100:.2f} & {mark} \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\vspace{2pt}\footnotesize",
        r"Per-seed picks: "
        + ", ".join(rf"seed {s} $\rightarrow$ $\lambda{{=}}{v}$" for s, v in sorted(picks.items()))
        + r". The main configuration of the paper ($\lambda{=}3$) is the one fixed before the "
        r"grid's remaining seeds landed; this experiment asks whether a held-out protocol "
        r"selects the same point, not whether we ran one when the configuration was fixed.",
        r"\end{table}",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    print(text)
    if args.check:
        if not OUT.exists():
            raise SystemExit(f"[--check] {OUT} 不存在")
        if OUT.read_text(encoding="utf-8") != text + "\n":
            raise SystemExit("[--check] 与 reports/val_selection.json 不一致")
        print("[--check] OK")
        return
    OUT.write_text(text + "\n", encoding="utf-8")
    print(f"已写入 {OUT}")


if __name__ == "__main__":
    main()
